/**
 * Put the list in the database, once.
 *
 * Insert-if-absent by code, and nothing is ever restated: an item the
 * clinic has renamed, repriced in units or switched off stays as the
 * clinic left it. A seed list that overwrites the clinic on every boot is
 * one that teaches people not to use the screen.
 */
function load(db) {
  const findArea = db.prepare('SELECT code FROM consumable_areas WHERE code = ?');
  const addArea = db.prepare(
    'INSERT INTO consumable_areas (code, label, sort_order) VALUES (?, ?, ?)');
  const findItem = db.prepare('SELECT id FROM consumables WHERE code = ?');
  const addItem = db.prepare(
    `INSERT INTO consumables (code, name, description, area, unit, indent_qty, seeded, sort_order)
     VALUES (?, ?, ?, ?, ?, ?, 1, ?)`
  );

  let areas = 0;
  let added = 0;
  db.transaction(() => {
    for (const a of AREAS) {
      if (findArea.get(a.code)) continue;
      addArea.run(a.code, a.label, a.sort);
      areas += 1;
    }
    ITEMS.forEach((it, i) => {
      if (findItem.get(it.code)) return;
      addItem.run(it.code, it.name, it.description || null, it.area, it.unit, it.indent, (i + 1) * 10);
      added += 1;
    });
  })();
  return { areas, added, total: ITEMS.length };
}

module.exports = { AREAS, ITEMS, load };
